"""Write reports/RESULTS.md from saved run outputs (no training happens here).

    python scripts/make_results_report.py --final-config s01_big_legacy --release-model models/triplevar_v1.pt
"""

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from triplevar.dataset import FeatureSet
from triplevar.ensemble import load_model
from triplevar.metrics import Scores, binary_report, bootstrap_ci

EXTERNALS = {
    "clinvar_timesplit": ("ClinVar time-split (classified after training)", "data/processed/clinvar_timesplit"),
    "literature_abstract": ("Literature, abstract labels (15)", "data/processed/literature_abstract"),
    "literature_abstract_clean": ("Literature, abstract labels, training overlap removed (11)", "data/processed/literature_abstract_clean"),
    "lit_transport": ("Literature, uptake rule (Li 2024)", "data/processed/lit_transport"),
    "lit_binding": ("Literature, binding rule (Gabriel 2024)", "data/processed/lit_binding"),
}


def pct(x):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{100 * x:.1f}%"


def f3(x):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.3f}"


def ext_rows(model, rule: str):
    rows = []
    for key, (label, path) in EXTERNALS.items():
        fs = FeatureSet.load(path)
        fs = fs.subset(fs.meta["label_binary"].notna().to_numpy())
        y = fs.meta["label_binary"].astype(int).to_numpy() == 1
        s = Scores(model.predict_proba(fs.X(model.layout)))
        score = s.strict_pathogenic if rule == "strict" else s.pathogenic_given_variant
        call = (score > 0.5) if rule == "strict" else s.call_grouped()
        r = binary_report(y, call, score)
        ci = bootstrap_ci(y, score) if r.auc is not None else [np.nan, np.nan]
        rows.append((label, r, ci, fs, s))
    return rows


def ext_table(rows) -> str:
    out = ["| External set | n (P/B) | Accuracy | Precision | Recall | Specificity | AUC [95% CI] |", "|---|---|---|---|---|---|---|"]
    for label, r, ci, _, _ in rows:
        out.append(f"| {label} | {r.n} ({r.tp + r.fn}/{r.fp + r.tn}) | {pct(r.accuracy)} | {pct(r.precision)} | "
                   f"{pct(r.recall)} | {pct(r.specificity)} | {f3(r.auc)} [{f3(ci[0])}–{f3(ci[1])}] |")
    return "\n".join(out)


def subgroup_table(fs: FeatureSet, s: Scores) -> str:
    meta = fs.meta.reset_index(drop=True)
    y = meta["label_binary"].astype(int).to_numpy() == 1
    call, score = s.call_grouped(), s.pathogenic_given_variant
    groups = {
        "all": np.ones(len(meta), bool),
        "with published frequency features": (meta["feature_source"] == "published_features").to_numpy(),
        "new variants, no frequency data": (meta["feature_source"] != "published_features").to_numpy(),
        "missense": meta["is_missense"].fillna(False).astype(bool).to_numpy(),
        "no ClinVar submission before the snapshot": meta.get("strict_temporal", pd.Series(False, index=meta.index)).fillna(False).astype(bool).to_numpy(),
    }
    out = ["| Subset | n (P/B) | Accuracy | Recall | Specificity | AUC |", "|---|---|---|---|---|---|"]
    for name, m in groups.items():
        if m.sum() == 0:
            continue
        r = binary_report(y[m], call[m], score[m])
        out.append(f"| {name} | {r.n} ({r.tp + r.fn}/{r.fp + r.tn}) | {pct(r.accuracy)} | {pct(r.recall)} | {pct(r.specificity)} | {f3(r.auc)} |")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--abstract-dir", default="reports/abstract_reproduction")
    ap.add_argument("--abstract-model", default="models/triplevar_abstract_2025-09-11.pt")
    ap.add_argument("--abstract-protocol", default="reports/experiments/abstract_protocol.summary.json")
    ap.add_argument("--search-dir", default="reports/experiments/search")
    ap.add_argument("--final-config", required=True)
    ap.add_argument("--final-summary", default="reports/experiments/production.summary.json")
    ap.add_argument("--release-model", required=True)
    ap.add_argument("--out", default="reports/RESULTS.md")
    args = ap.parse_args()

    rep = json.loads(Path(args.abstract_dir, "abstract_reproduction.json").read_text())
    st, pl = rep["clinvar_test"]["strict_P_vs_B"], rep["clinvar_test"]["PLP_vs_BLB"]
    lit = rep["literature_external"]["rule_strict_ratio_gt_0.5"]
    pr = rep["prioritised"]
    md = ["# TripleVar results", "", "Generated by `scripts/make_results_report.py`.", ""]
    md += ["## 1. The submitted abstract, reproduced", "",
           "Model `best_model__(2025_09_11)_16|13.pt` (released as `models/triplevar_abstract_2025-09-11.pt`) on the "
           "published row-level split (604 / 130 / 130 ClinVar variants + 962 wild-type rows).", "",
           "| Claim | Abstract | Reproduced |", "|---|---|---|",
           f"| ClinVar test, P vs B: accuracy / precision / recall / specificity / F1 | 93.3 / 100 / 84.6 / 100 / 91.7 % | "
           f"{pct(st['accuracy'])} / {pct(st['precision'])} / {pct(st['recall'])} / {pct(st['specificity'])} / {pct(st['f1'])} |",
           f"| ClinVar test, P vs B: AUC | 1.0 | {f3(st['auc'])} |",
           f"| ClinVar test incl. LP/LB: accuracy / AUC | 93.7 % / 0.913 | {pct(pl['accuracy'])} / {f3(pl['auc_renormalised'])} |",
           f"| Literature set (15): accuracy / precision / recall / specificity | 80 / 90 / 82 / 75 % | "
           f"{pct(lit['accuracy'])} / {pct(lit['precision'])} / {pct(lit['recall'])} / {pct(lit['specificity'])} (see note) |",
           f"| Prioritised pathogenic / likely pathogenic (pool + VUS) | 111 / 303 | {pr['pathogenic_high_confidence']} / {pr['likely_pathogenic_lower_confidence']} |",
           "", "Note: the literature numbers in the abstract came from an unsaved run earlier the same day; the saved "
           "checkpoint gives the same accuracy (12/15) with one more false positive and one fewer false negative.", ""]

    if Path(args.abstract_protocol).exists():
        ap_m = json.loads(Path(args.abstract_protocol).read_text())["metrics"]
        g = lambda k: ap_m.get(k, {"mean": np.nan, "sd": np.nan})  # noqa: E731
        md += ["Re-running the abstract's training protocol with 5 fixed seeds (same split) gives "
               f"P-vs-B accuracy {pct(g('test.strict_P_vs_B.accuracy')['mean'])} ± {100 * g('test.strict_P_vs_B.accuracy')['sd']:.1f} "
               f"and AUC {f3(g('test.strict_P_vs_B.auc')['mean'])}, P/LP-vs-B/LB AUC {f3(g('test.PLP_vs_BLB.auc_renormalised')['mean'])}: "
               "the abstract numbers are typical for that protocol, not a lucky seed.", ""]

    abstract_model = load_model(args.abstract_model)
    md += ["## 2. External validation of the abstract model", "",
           "Binary call = P(pathogenic)/(P(pathogenic)+P(benign)) > 0.5, the rule used for the abstract.", "",
           ext_table(ext_rows(abstract_model, "strict")), ""]

    md += ["## 3. Leakage-free evaluation and model selection", "",
           "Grouped 10-fold cross-validation by rsID (all alleles of an rsID and its wild-type row stay together), "
           "2 repeats; early stopping on a separate validation fold. Configurations were compared on the "
           "out-of-fold AUC for P/LP vs B/LB on rows whose label belongs to their own allele ('trusted'); "
           "external sets were never used for selection.", ""]
    rows = []
    for p in sorted(Path(args.search_dir).glob("*.summary.json")):
        s = json.loads(p.read_text())
        m = s["metrics"]
        get = lambda k: m.get(k, {}).get("mean", np.nan)  # noqa: E731
        rows.append((s["config"], get("test.PLP_vs_BLB.auc_renormalised"), get("test_clean.PLP_vs_BLB.auc_renormalised"),
                     get("test.strict_P_vs_B.auc"), get("test.PLP_vs_BLB.accuracy"), get("test.PLP_vs_BLB.recall"),
                     get("test.PLP_vs_BLB.specificity")))
    md += ["| Config | CV AUC (P/LP vs B/LB) | CV AUC, trusted labels | CV AUC (P vs B) | CV accuracy | CV recall | CV specificity |",
           "|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: -np.nan_to_num(r[2])):
        name = f"**{r[0]}**" if r[0] == args.final_config else r[0]
        md.append(f"| {name} | " + " | ".join(f3(v) if i < 3 else pct(v) for i, v in enumerate(r[1:])) + " |")
    md += ["", "Configs: `s*` = full model variants, `a*` = modality ablations (small network); see `configs/search/`.", ""]

    if args.final_summary and Path(args.final_summary).exists():
        fm = json.loads(Path(args.final_summary).read_text())["metrics"]
        ms = lambda k, p=False: ("n/a" if k not in fm else  # noqa: E731
                                 (f"{100 * fm[k]['mean']:.1f} ± {100 * fm[k]['sd']:.1f} %" if p else f"{fm[k]['mean']:.3f} ± {fm[k]['sd']:.3f}"))
        md += [f"### Selected configuration (`configs/production.yaml`), 10-fold grouped CV × {fm['test.PLP_vs_BLB.auc_renormalised']['n']} repeats", "",
               "| Metric | All labels | Trusted labels |", "|---|---|---|"]
        for label, key, p in [("P/LP vs B/LB AUC", "PLP_vs_BLB.auc_renormalised", False), ("P/LP vs B/LB accuracy", "PLP_vs_BLB.accuracy", True),
                              ("P/LP vs B/LB precision", "PLP_vs_BLB.precision", True), ("P/LP vs B/LB recall", "PLP_vs_BLB.recall", True),
                              ("P/LP vs B/LB specificity", "PLP_vs_BLB.specificity", True), ("P vs B AUC", "strict_P_vs_B.auc", False),
                              ("P vs B accuracy", "strict_P_vs_B.accuracy", True)]:
            md.append(f"| {label} | {ms('test.' + key, p)} | {ms('test_clean.' + key, p)} |")
        md += ["", "Fold-model ensembles of the same runs on the external sets (grouped-argmax call, renormalised score):", "",
               "| External set | Accuracy | Recall | Specificity | AUC |", "|---|---|---|---|---|"]
        for name in ("clinvar_timesplit", "literature", "literature_clean", "lit_transport", "lit_binding"):
            base = f"external:{name}.grouped_argmax."
            if base + "auc" in fm:
                md.append(f"| {name} | {ms(base + 'accuracy', True)} | {ms(base + 'recall', True)} | {ms(base + 'specificity', True)} | {ms(base + 'auc')} |")
        md.append("")

    release = load_model(args.release_model)
    rows = ext_rows(release, "grouped")
    n_members = len(getattr(release, "members", [release]))
    md += [f"## 4. Release model `{Path(args.release_model).name}` on the external sets", "",
           f"Config `{args.final_config}` (= `configs/production.yaml`), {n_members}-seed ensemble; each member is trained "
           "on all labeled rsIDs except one grouped fold (different per seed) used for early stopping. "
           "Call = 5-class argmax grouped into pathogenic vs benign; score for AUC = P(P or LP) renormalised over "
           "the four variant classes.", "", ext_table(rows), "",
           "### ClinVar time-split subsets", "", subgroup_table(rows[0][3], rows[0][4]), "",
           "### Why an ensemble",
           "",
           "Single release models of the four configurations tied on cross-validation called 2.9–10.9 % of the "
           "28,764 non-coding pool variants pathogenic; 5-seed ensembles of the same configurations called 2.5–3.7 % "
           "(the abstract model: 0.7 %). The configuration chosen by cross-validation was kept; the release procedure "
           "changed from one model to an ensemble.", ""]
    counts_csv = Path("reports/predictions") / f"prioritisation_counts.{Path(args.release_model).stem}.csv"
    if counts_csv.exists():
        c = pd.read_csv(counts_csv, index_col=0)
        table = ["| Source | " + " | ".join(c.columns) + " |", "|---|" + "---|" * len(c.columns)]
        table += [f"| {i} | " + " | ".join(str(v) for v in row) + " |" for i, row in c.iterrows()]
        md += ["## 5. Prioritisation (VUS + unlabeled dbSNP variants)", "", *table, "",
               f"Ranked list: `reports/predictions/prioritised_pathogenic.{Path(args.release_model).stem}.csv`.", ""]
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
