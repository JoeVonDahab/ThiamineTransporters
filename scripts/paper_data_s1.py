"""Supplementary Data S1 of the manuscript -> reports/supplementary/.

    python scripts/export_predictions.py --model models/triplevar_v1.pt   # writes reports/predictions/
    python scripts/paper_data_s1.py

DataS1a: release-model predictions for the 97 ClinVar time-split variants.
DataS1b: release-model predictions for every unclassified allele (ClinVar VUS and unlabelled
dbSNP alleles), ranked by P(pathogenic or likely pathogenic).
DataS1_README.md: column dictionary.
"""

import re
from pathlib import Path

import pandas as pd

PRED = Path("reports/predictions")
OUT = Path("reports/supplementary")
TAG = "triplevar_v1"

CONSEQUENCE_GROUPS = [  # same grouping as Figure 3b (scripts/paper_figures.py)
    ("frameshift", "Frameshift"), ("nonsense", "Nonsense"), ("splice", "Splice site"),
    ("missense", "Missense"), ("synonymous", "Synonymous"), ("intron|UTR|upstream", "Intronic / UTR"),
]
CLASS_NAMES = {"Normal": "Reference"}
PROBS = {"p_P": "p_P", "p_LP": "p_LP", "p_LB": "p_LB", "p_B": "p_B", "p_normal": "p_reference", "p_pathogenic": "p_pathogenic"}


def consequence_group(text):
    for pattern, name in CONSEQUENCE_GROUPS:
        if re.search(pattern, str(text)):
            return name
    return "Other"


def as_bool(s):
    return s.astype(str).str.lower().isin(["true", "1", "1.0"])


def as_int(s):
    return pd.to_numeric(s, errors="coerce").round().astype("Int64")


def predictions(df):
    out = pd.DataFrame({new: df[old].round(6) for old, new in PROBS.items()})
    out["predicted_class"] = df["predicted_class"].replace(CLASS_NAMES)
    out["pathogenic_call"] = as_bool(df["pathogenic_call"])
    return out


def data_s1a():
    ts = pd.read_csv(PRED / f"clinvar_timesplit.{TAG}.csv")
    a = pd.DataFrame({
        "gene": ts["gene"],
        "chrom": as_int(ts["chrom"]),
        "pos_grch38": as_int(ts["pos"]),
        "ref": ts["ref"],
        "alt": ts["alt"],
        "hgvs_c": ts["hgvs_c"],
        "hgvs_p": ts["hgvs_p"],
        "transcript": ts["transcript"],
        "consequence": ts["consequence"],
        "consequence_group": ts["consequence"].map(consequence_group),
        "variant_type": ts["variant_type"],
        "clinvar_variation_id": as_int(ts["variation_id"]),
        "clinvar_classification": ts["clinvar_classification"],
        "label": ts["label_binary"].astype(int).map({1: "P/LP", 0: "B/LB"}),
        "review_status": ts["review_status"],
        "last_evaluated": ts["last_evaluated"],
        "dbsnp_rsid": as_int(ts["train_snp_id"]).map(lambda x: f"rs{x}" if pd.notna(x) else pd.NA),
        "in_training_export": ts["feature_source"].eq("published_features"),
        "no_clinvar_submission_before_snapshot": as_bool(ts["strict_temporal"].fillna(False)),
        "is_missense": as_bool(ts["is_missense"].fillna(False)),
        "training_label_in_export": ts["training_label"],
    })
    a = pd.concat([a, predictions(ts)], axis=1)
    assert len(a) == 97 and a["label"].notna().all()
    return a


def data_s1b():
    p = pd.read_csv(PRED / f"prioritisation_all.{TAG}.csv")
    b = pd.DataFrame({
        "rank": range(1, len(p) + 1),
        "source": p["source"].replace({"dbSNP unlabeled": "dbSNP unclassified"}),
        "gene": p["gene"],
        "dbsnp_rsid": "rs" + p["snp_id"].astype(str),
        "chrom": as_int(p["#chr"]),
        "pos_dbsnp": as_int(p["pos"]),
        "ref_dbsnp": p["original"],
        "alt_dbsnp": p["mutant"],
        "variant_type": p["variant_type"],
        "function_class": p["function_class"],
        "clinical_significance_in_export": p["clinical_significance"],
    })
    b = pd.concat([b, predictions(p)], axis=1)
    assert b["p_pathogenic"].is_monotonic_decreasing
    return b


README = """# Supplementary Data S1

Predictions of the released TripleVar model (`models/triplevar_v1.pt`, average of five networks) for
"Rigorous evaluation of a multimodal language-model classifier for thiamine transporter variants".
Generated by `scripts/paper_data_s1.py` in https://github.com/JoeVonDahab/ThiamineTransporters.

Common prediction columns (both files):

| Column | Meaning |
|---|---|
| p_P, p_LP, p_LB, p_B | Model probability of pathogenic, likely pathogenic, likely benign and benign |
| p_reference | Probability of the synthetic wild-type reference class (used only in training) |
| p_pathogenic | TripleVar score: (p_P + p_LP) / (p_P + p_LP + p_LB + p_B) |
| predicted_class | Categorical call (most probable class, reference-class calls resolved as in the Methods) |
| pathogenic_call | TRUE if predicted_class is P or LP, or if it is Reference and p_P + p_LP > p_LB + p_B |

## DataS1a_clinvar_timesplit.csv ({n_a} variants)

Variants classified as P, LP, LB or B in ClinVar (October 2026) that were unlabeled, VUS or absent in the
June 2025 dbSNP export used for training, plus SLC19A2 p.Asp93His from UniProt.

| Column | Meaning |
|---|---|
| gene, chrom, pos_grch38, ref, alt | Variant on GRCh38 (VCF-style alleles) |
| hgvs_c, hgvs_p, transcript | HGVS description on the ClinVar transcript |
| consequence, consequence_group | ClinVar molecular consequence; grouping used in Figure 3b |
| variant_type | ClinVar variant type |
| clinvar_variation_id | ClinVar VariationID (empty for the UniProt variant) |
| clinvar_classification, label | ClinVar germline classification; binary label (P/LP or B/LB) |
| review_status, last_evaluated | ClinVar review status and date last evaluated |
| dbsnp_rsid | dbSNP record of the matching row in the training export (empty if absent) |
| in_training_export | TRUE if the variant was in the export (scored with its original features); FALSE if embedded de novo without population data |
| no_clinvar_submission_before_snapshot | TRUE if no ClinVar submission for the variant existed before 27 June 2025 |
| is_missense | Missense single-nucleotide variant |
| training_label_in_export | Label of the variant in the training export (empty = unlabeled or absent) |

## DataS1b_unclassified_ranked.csv ({n_b} alleles)

All {n_vus} ClinVar VUS and {n_pool} unclassified dbSNP alleles, ranked by p_pathogenic ({n_call} with pathogenic_call TRUE).

| Column | Meaning |
|---|---|
| rank | Rank by p_pathogenic (1 = highest) |
| source | ClinVar VUS (labelled VUS in the export) or dbSNP unclassified |
| gene, dbsnp_rsid | Gene and dbSNP record |
| chrom, pos_dbsnp, ref_dbsnp, alt_dbsnp | Allele in dbSNP notation (GRCh38; "-" denotes an empty allele) |
| variant_type, function_class | dbSNP variant type and function class |
| clinical_significance_in_export | Clinical significance string of the record in the June 2025 export |

These are research predictions. TripleVar was outperformed by CADD, AlphaMissense and REVEL on shared
variants and is not validated for clinical variant classification.
"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    a, b = data_s1a(), data_s1b()
    a.to_csv(OUT / "DataS1a_clinvar_timesplit.csv", index=False)
    b.to_csv(OUT / "DataS1b_unclassified_ranked.csv", index=False)
    counts = b["source"].value_counts()
    (OUT / "DataS1_README.md").write_text(README.format(
        n_a=len(a), n_b=f"{len(b):,}", n_vus=f"{counts['ClinVar VUS']:,}", n_pool=f"{counts['dbSNP unclassified']:,}",
        n_call=f"{int(b['pathogenic_call'].sum()):,}"))
    print(f"DataS1a {len(a)} rows; DataS1b {len(b)} rows ({dict(counts)}), {int(b['pathogenic_call'].sum())} P/LP calls")
    print("S1a calls correct:", int((a["pathogenic_call"] == a["label"].eq("P/LP")).sum()), "of", len(a))
    print("predicted classes S1b:", dict(b["predicted_class"].value_counts()))


if __name__ == "__main__":
    main()
